import { readFileSync, existsSync } from 'node:fs'
import { resolve } from 'node:path'

/**
 * The native assets, against the rules the stores enforce on upload.
 *
 * These fail at submission, not at build — so without a gate the first anybody
 * knows is a rejected upload after a twenty-minute build, and the fix is a
 * rebuild rather than a retry.
 *
 * The rule that caught this project: **App Store validation refuses an app icon
 * with an alpha channel**, and it refuses a fully-opaque RGBA file too. The
 * channel's presence is the fault, not its contents. Quantising is what
 * introduced it — a palette PNG carries a `tRNS` entry even when nothing in it
 * is transparent — so the icon looked right, passed every other check, and
 * would have failed on the first upload.
 *
 * The opposite is true of the other two, which is why this is a per-asset rule
 * rather than a blanket one:
 *
 *   - the splash image sits on a background colour, so its rounded corners
 *     need to be transparent;
 *   - an Android adaptive foreground is composited over a separate background
 *     layer, so alpha is the entire mechanism.
 *
 * Generated by `scripts/make-brand-assets.py`, which is where a fix belongs —
 * editing a PNG by hand would be undone by the next run.
 */

const ASSETS = [
  {
    path: 'apps/mobile/assets/images/icon.png',
    alpha: false,
    why: 'App Store validation rejects an app icon with an alpha channel',
  },
  {
    path: 'apps/mobile/assets/images/splash-icon.png',
    alpha: true,
    why: 'it sits on a background colour, so its rounded corners must be transparent',
  },
  {
    path: 'apps/mobile/assets/images/android-icon-foreground.png',
    alpha: true,
    why: 'an adaptive foreground is composited over the background layer',
  },
]

const fails = []
const ok = (cond, msg, measured) => {
  console.log(`${cond ? 'PASS' : 'FAIL'}  ${msg}${measured ? `  (${measured})` : ''}`)
  if (!cond) fails.push(msg)
}

/**
 * Whether a PNG can carry transparency, read from the file itself.
 *
 * Two ways it can, and both count. The IHDR colour type says so directly for
 * truecolour-with-alpha (6) and greyscale-with-alpha (4); a palette image (3)
 * says so with a `tRNS` chunk instead, which is the case that slipped through.
 */
function pngAlpha(bytes) {
  if (bytes.readUInt32BE(0) !== 0x89504e47) throw new Error('not a PNG')
  const colourType = bytes[25]
  if (colourType === 4 || colourType === 6) return { alpha: true, how: `colour type ${colourType}` }

  // Walk the chunks looking for tRNS. Offset 8 is the first chunk's length.
  let at = 8
  while (at + 8 <= bytes.length) {
    const length = bytes.readUInt32BE(at)
    const type = bytes.toString('ascii', at + 4, at + 8)
    if (type === 'tRNS') return { alpha: true, how: 'tRNS chunk' }
    if (type === 'IEND') break
    at += 12 + length
  }
  return { alpha: false, how: `colour type ${colourType}, no tRNS` }
}

for (const asset of ASSETS) {
  const full = resolve(asset.path)
  if (!existsSync(full)) {
    ok(false, `${asset.path} is missing`)
    continue
  }
  const { alpha, how } = pngAlpha(readFileSync(full))
  const name = asset.path.split('/').pop()
  ok(
    alpha === asset.alpha,
    asset.alpha
      ? `${name} keeps its alpha channel — ${asset.why}`
      : `${name} has no alpha channel — ${asset.why}`,
    how,
  )
}

console.log(
  fails.length
    ? `\n${fails.length} asset(s) would be refused or would render wrong. Fix the generator, not the PNG: python3 scripts/make-brand-assets.py`
    : '\nThe native assets match what the stores accept.',
)
process.exit(fails.length ? 1 : 0)
